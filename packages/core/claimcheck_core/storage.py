"""Object storage through the S3 API (B2, AD-11). Locally MinIO (http://127.0.0.1:9000, bucket
`claimcheck-dev`); production S3 in ca-central-1 with server-side encryption, selected by settings alone.

Keys isolate tenant, source and purpose (R-13): `clinic/<clinic_id>/<source>/<purpose>/<object_id>.<ext>`,
with source and purpose from closed lists and every part generated by the server. Callers never pass a
key: they use `ClinicObjects`, which is bound to one clinic and builds keys under that clinic's prefix
only, so a request for another clinic's object cannot even be expressed. No public URLs are produced;
downloads go through an authorised API endpoint.
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from functools import lru_cache
from typing import TYPE_CHECKING, Any, Protocol

from claimcheck_core.settings import get_settings

if TYPE_CHECKING:
    from mypy_boto3_s3.client import S3Client

SOURCES = frozenset({"jane_export"})
PURPOSES = frozenset({"import_payload"})
EXTENSIONS = frozenset({"json"})


class ObjectMissing(LookupError):
    pass


def clinic_prefix(clinic_id: uuid.UUID) -> str:
    if not isinstance(clinic_id, uuid.UUID):
        raise TypeError("clinic_id must be a UUID")
    return f"clinic/{clinic_id}/"


def object_key(clinic_id: uuid.UUID, source: str, purpose: str, object_id: uuid.UUID, ext: str = "json") -> str:
    if source not in SOURCES or purpose not in PURPOSES or ext not in EXTENSIONS:
        raise ValueError("unknown source, purpose or extension")
    if not isinstance(object_id, uuid.UUID):
        raise TypeError("object_id must be a UUID")
    return f"{clinic_prefix(clinic_id)}{source}/{purpose}/{object_id}.{ext}"


class BlobStore(Protocol):
    def put(self, key: str, data: bytes, content_type: str) -> None: ...
    def get(self, key: str) -> bytes: ...
    def delete(self, key: str) -> None: ...
    def list_keys(self, prefix: str) -> list[str]: ...


class S3BlobStore:
    def __init__(self, client: S3Client, bucket: str, sse: str | None = None) -> None:
        self._c = client
        self._bucket = bucket
        self._sse = sse

    def put(self, key: str, data: bytes, content_type: str) -> None:
        extra: dict[str, Any] = {"ServerSideEncryption": self._sse} if self._sse else {}
        self._c.put_object(Bucket=self._bucket, Key=key, Body=data, ContentType=content_type, **extra)

    def get(self, key: str) -> bytes:
        try:
            obj = self._c.get_object(Bucket=self._bucket, Key=key)
        except self._c.exceptions.NoSuchKey:
            raise ObjectMissing(key) from None
        return obj["Body"].read()

    def delete(self, key: str) -> None:
        self._c.delete_object(Bucket=self._bucket, Key=key)

    def list_keys(self, prefix: str) -> list[str]:
        keys: list[str] = []
        for page in self._c.get_paginator("list_objects_v2").paginate(Bucket=self._bucket, Prefix=prefix):
            keys += [o["Key"] for o in page.get("Contents", []) if "Key" in o]
        return keys


@dataclass
class MemoryBlobStore:
    """Test double."""

    objects: dict[str, bytes] = field(default_factory=dict)

    def put(self, key: str, data: bytes, content_type: str) -> None:
        self.objects[key] = data

    def get(self, key: str) -> bytes:
        if key not in self.objects:
            raise ObjectMissing(key)
        return self.objects[key]

    def delete(self, key: str) -> None:
        self.objects.pop(key, None)

    def list_keys(self, prefix: str) -> list[str]:
        return sorted(k for k in self.objects if k.startswith(prefix))


class ClinicObjects:
    """The only way application code reaches the store: bound to one clinic."""

    def __init__(self, store: BlobStore, clinic_id: uuid.UUID) -> None:
        self._store = store
        self._clinic = clinic_id
        self._prefix = clinic_prefix(clinic_id)

    def key(self, source: str, purpose: str, object_id: uuid.UUID) -> str:
        return object_key(self._clinic, source, purpose, object_id)

    def _own(self, key: str) -> str:
        if not key.startswith(self._prefix):
            raise PermissionError("key outside this clinic's prefix")
        return key

    def put(self, source: str, purpose: str, object_id: uuid.UUID, data: bytes,
            content_type: str = "application/json") -> str:
        key = self.key(source, purpose, object_id)
        self._store.put(key, data, content_type)
        return key

    def get(self, key: str) -> bytes:
        return self._store.get(self._own(key))

    def delete(self, key: str) -> None:
        self._store.delete(self._own(key))

    def delete_all(self) -> int:
        """Clinic deletion (MH-11 b): every object under the clinic's prefix."""
        keys = self._store.list_keys(self._prefix)
        for k in keys:
            self._store.delete(k)
        return len(keys)


def make_s3_store() -> S3BlobStore:
    import boto3
    from botocore.config import Config

    s = get_settings()
    client = boto3.client(
        "s3", endpoint_url=s.s3_endpoint_url, region_name=s.s3_region,
        aws_access_key_id=s.s3_access_key_id, aws_secret_access_key=s.s3_secret_access_key,
        config=Config(signature_version="s3v4", s3={"addressing_style": "path"},
                      connect_timeout=5, read_timeout=20, retries={"max_attempts": 3}),
    )
    return S3BlobStore(client, s.s3_bucket, s.s3_server_side_encryption)


@lru_cache(maxsize=1)
def get_store() -> BlobStore:
    return make_s3_store()
